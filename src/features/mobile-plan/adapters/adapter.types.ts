// 사이트마다 HTML 구조는 다르지만, "요금제 목록을 수집한다"는 겉모습(인터페이스)은
// 똑같이 맞춘다. 그래야 수집기(collector)가 어떤 사이트든 동일하게 다룰 수 있다.
// => 새 사이트가 생기면 이 인터페이스를 구현한 파일 하나만 추가하면 된다. (캡슐화)
// =============================================================================

import type { MobilePlan } from "@/shared/types";

/** 수집 시 공통 옵션 */
export interface CollectOptions {
  maxPages: number; // 최대 몇 페이지까지 순회할지 (버튼 클릭 시 빠른 응답을 위해 제한)
  delayMs: number; // 페이지 사이 대기 시간 (사이트 부담 완화용 예의상 딜레이)
}

/** 모든 알뜰폰 수집 어댑터가 구현해야 하는 형태 */
export interface PlanCollectorAdapter {
  /** 출처 사이트명 (결과에 표시되고 중복 제거에도 쓰임) */
  readonly source: string;

  /**
   * 실제 크롤링이 구현되어 동작하는지 여부.
   * false 이면 아직 제휴/구현 전이라 예시(Mock) 데이터만 돌려준다. (PRD 8장 원칙)
   */
  readonly isReal: boolean;

  /** 요금제 목록을 수집해 구조화된 배열로 반환한다. */
  collect(options: CollectOptions): Promise<MobilePlan[]>;
}
